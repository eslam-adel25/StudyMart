// Restore custom created/edited books & filter deleted books from localStorage if available
try {
  if (typeof localStorage !== "undefined") {
    const deletedRaw = localStorage.getItem("studymart_deleted_books");
    const deletedIds = deletedRaw ? JSON.parse(deletedRaw) : [];

    if (Array.isArray(deletedIds) && deletedIds.length > 0) {
      for (let i = booksData.length - 1; i >= 0; i--) {
        if (deletedIds.map(String).includes(String(booksData[i].id))) {
          booksData.splice(i, 1);
        }
      }
    }

    const saved = localStorage.getItem("studymart_custom_books");
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        parsed.forEach((customBook) => {
          if (!customBook || !customBook.id) return;
          if (deletedIds.map(String).includes(String(customBook.id))) return;

          const idx = booksData.findIndex((b) => String(b.id) === String(customBook.id));
          if (idx >= 0) {
            booksData[idx] = customBook;
          } else {
            booksData.push(customBook);
          }
        });
      }
    }
  }
} catch (e) {
  console.error("Error restoring custom books from localStorage:", e);
}
